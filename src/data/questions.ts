export const QUESTIONS: Question[] = QUESTIONS_POOL.slice(0, 40);

/**
 * 200개 대규모 문항 풀에서 각 성향 축(EI, SN, TF, JP)별로 균형 있게 countPerDimension 개씩 무작위 추출하여 섞습니다.
 * @param countPerDimension 축당 추출할 문항 수 (기본값: 10개 -> 총 40문항)
 */
export function getRandomQuestions(countPerDimension = 10): Question[] {
  const pickRandom = (arr: Question[], n: number) => {
    const shuffled = [...arr].sort(() => Math.random() - 0.5);
    return shuffled.slice(0, n);
  };

  const ei = pickRandom(
    QUESTIONS_POOL.filter((q) => q.dimension === 'EI'),
    countPerDimension,
  );
  const sn = pickRandom(
    QUESTIONS_POOL.filter((q) => q.dimension === 'SN'),
    countPerDimension,
  );
  const tf = pickRandom(
    QUESTIONS_POOL.filter((q) => q.dimension === 'TF'),
    countPerDimension,
  );
  const jp = pickRandom(
    QUESTIONS_POOL.filter((q) => q.dimension === 'JP'),
    countPerDimension,
  );

  const combined = [...ei, ...sn, ...tf, ...jp];
  // 4개 축의 문항을 고르게 섞음
  return combined.sort(() => Math.random() - 0.5);
}
